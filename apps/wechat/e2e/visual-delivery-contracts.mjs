function delivery(
  figmaNodeId,
  scenarioId,
  route,
  semanticSelector,
  requiredText,
  primarySelector,
  textSelector,
) {
  return {
    figmaNodeId,
    scenarioId,
    route,
    semanticSelector,
    requiredText,
    ...(primarySelector ? { primarySelector } : {}),
    ...(textSelector ? { textSelector } : {}),
  };
}

function deliveryState(
  figmaNodeId,
  scenarioId,
  route,
  routeState,
  semanticSelector,
  requiredText,
  primarySelector,
  textSelector,
) {
  return {
    ...delivery(
      figmaNodeId,
      scenarioId,
      route,
      semanticSelector,
      requiredText,
      primarySelector,
      textSelector,
    ),
    routeState,
  };
}
