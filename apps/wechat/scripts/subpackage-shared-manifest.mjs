export function subpackageSharedDestination(path, packageName) {
  if (path === "features/essay-task/forms.ts") return "pages/essay-task/features/forms.ts";
  if (path === "features/positions/contracts.ts") return "pages/positions/features/contracts.ts";
  const packageRoot =
    {
      plans: "plans",
      account: "account",
      xingce: "xingce",
      essay: "essay",
      community: "community",
      reports: "reports",
    }[packageName] ?? `pages/${packageName}`;
  return `${packageRoot}/shared/${path}`;
}
