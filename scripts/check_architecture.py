#!/usr/bin/env python3
"""Enforce repository boundaries that are expensive to repair after feature growth."""

from __future__ import annotations

import ast
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
BACKEND_APP = ROOT / "backend" / "app"
GENERATED_TYPES = (
    ROOT / "apps" / "wechat" / "miniprogram" / "api" / "generated" / "types.gen.ts"
)


def imported_modules(path: Path) -> list[tuple[int, str]]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    imports: list[tuple[int, str]] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imports.extend((node.lineno, alias.name) for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imports.append((node.lineno, node.module))
    return imports


def check_backend_boundaries() -> list[str]:
    errors: list[str] = []
    forbidden_by_layer = {
        "platform": ("app.api", "app.domains", "app.importers"),
        "core": ("app.api", "app.db", "app.domains", "app.importers", "app.platform"),
        "db": ("app.api", "app.domains", "app.importers"),
    }

    for layer, forbidden_prefixes in forbidden_by_layer.items():
        for path in sorted((BACKEND_APP / layer).rglob("*.py")):
            for line, module in imported_modules(path):
                if module.startswith(forbidden_prefixes):
                    relative = path.relative_to(ROOT)
                    errors.append(
                        f"{relative}:{line}: {layer} layer cannot import {module}"
                    )
    return errors


def check_generated_contract() -> list[str]:
    if not GENERATED_TYPES.is_file():
        return [f"missing generated API contract: {GENERATED_TYPES.relative_to(ROOT)}"]
    first_line = GENERATED_TYPES.read_text(encoding="utf-8").splitlines()[0]
    if first_line != "// This file is auto-generated by @hey-api/openapi-ts":
        return [
            "generated API contract is missing its ownership marker; "
            "regenerate it with npm run api:generate"
        ]
    return []


def main() -> int:
    errors = [*check_backend_boundaries(), *check_generated_contract()]
    if errors:
        print("Architecture checks failed:", file=sys.stderr)
        for error in errors:
            print(f"- {error}", file=sys.stderr)
        return 1
    print("Architecture boundaries: OK")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
